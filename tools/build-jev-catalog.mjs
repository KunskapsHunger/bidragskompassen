#!/usr/bin/env node
// Builds the grant catalogue the Jev search function ranks against, from the site's data files.
// The catalogue ships inside the Edge Function so callers can only ask questions, not supply options.
//   node tools/build-jev-catalog.mjs   → supabase/functions/bidragskompassen-sok/catalog.ts
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['grundskola', 'personal', 'gymnasium-vux', 'skolverket-ovriga', 'ovriga'];
const OUT = join(ROOT, 'supabase', 'functions', 'bidragskompassen-sok', 'catalog.ts');
const MAX_OPTION = 260;

const sandbox = { window: {} };
vm.createContext(sandbox);
for (const f of FILES) vm.runInContext(readFileSync(join(ROOT, 'data', `grants-${f}.js`), 'utf8'), sandbox);

const seen = new Set();
const grants = sandbox.window.SB_GRANTS.filter((g) => g.giltighet !== 'upphort' && !seen.has(g.id) && seen.add(g.id));

// Search words go before the summary so truncation never drops them — they carry everyday phrasing
// ("fler vuxna i skolan") that the official summary lacks.
const describe = (g) => {
  const words = (g.nyckelord || []).slice(0, 10).join(', ');
  const text = `${g.kortnamn} (${g.myndighet}).${words ? ` Sökord: ${words}.` : ''} ${g.sammanfattning}`;
  return text.length > MAX_OPTION ? `${text.slice(0, MAX_OPTION - 1)}…` : text;
};

const catalog = grants.map((g) => ({ id: g.id, text: describe(g) }));

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `// Generated by tools/build-jev-catalog.mjs — do not edit by hand.\n`
  + `export const CATALOG: { id: string; text: string }[] = [\n${catalog.map((c) => ` ${JSON.stringify(c)},`).join('\n')}\n];\n`);
console.log(`wrote ${catalog.length} grants to ${OUT}`);
